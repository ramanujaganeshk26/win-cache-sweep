"""Core scanner for Windows temporary files, crash dumps, and large file analysis."""

import os
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from pathlib import Path
from typing import Dict, List, Tuple


@dataclass
class ScanTarget:
    name: str
    path: Path
    category: str
    safety_level: str  # "SAFE", "CAUTION", "HIGH_RISK"
    description: str


@dataclass
class FileItem:
    path: Path
    size_bytes: int
    modified_time: datetime
    category: str
    safety_level: str
    reason: str


@dataclass
class ScanReport:
    total_scanned_bytes: int = 0
    scanned_files_count: int = 0
    category_totals: Dict[str, int] = field(default_factory=dict)
    items: List[FileItem] = field(default_factory=list)


class DiskScanner:
    def __init__(self, stale_days: int = 14):
        self.stale_days = stale_days

    @staticmethod
    def get_known_targets() -> List[ScanTarget]:
        targets = []
        
        # User Temp
        user_temp = os.getenv("TEMP") or os.getenv("TMP")
        if user_temp:
            targets.append(
                ScanTarget(
                    name="User Temp Directory",
                    path=Path(user_temp),
                    category="User Temp",
                    safety_level="SAFE",
                    description="Temporary files generated by user applications.",
                )
            )

        # System Temp
        sys_drive = os.getenv("SystemDrive", "C:")
        sys_temp = Path(sys_drive) / "Windows" / "Temp"
        targets.append(
            ScanTarget(
                name="System Temp Directory",
                path=sys_temp,
                category="System Temp",
                safety_level="SAFE",
                description="Temporary files created by system services.",
            )
        )

        # Crash Dumps
        local_app_data = os.getenv("LOCALAPPDATA")
        if local_app_data:
            crash_dumps = Path(local_app_data) / "CrashDumps"
            targets.append(
                ScanTarget(
                    name="User Crash Dumps",
                    path=crash_dumps,
                    category="Crash Dumps",
                    safety_level="SAFE",
                    description="Application crash memory dumps.",
                )
            )

        sys_dumps = Path(sys_drive) / "Windows" / "Minidump"
        targets.append(
            ScanTarget(
                name="System Minidumps",
                path=sys_dumps,
                category="Crash Dumps",
                safety_level="CAUTION",
                description="Windows kernel crash dumps.",
            )
        )

        # Windows Update Cache
        win_soft_dist = Path(sys_drive) / "Windows" / "SoftwareDistribution" / "Download"
        targets.append(
            ScanTarget(
                name="Windows Update Downloads",
                path=win_soft_dist,
                category="Update Cache",
                safety_level="SAFE",
                description="Downloaded Windows Update installation files.",
            )
        )

        return targets

    def scan_location(self, target: ScanTarget) -> List[FileItem]:
        items: List[FileItem] = []
        if not target.path.exists() or not target.path.is_dir():
            return items

        stale_threshold = datetime.now() - timedelta(days=self.stale_days)

        try:
            for entry in target.path.rglob("*"):
                if not entry.is_file():
                    continue
                try:
                    stat = entry.stat()
                    mtime = datetime.fromtimestamp(stat.st_mtime)
                    
                    # Safety adjustments based on staleness
                    safety = target.safety_level
                    reason = f"Located in {target.category}"
                    if mtime > stale_threshold and safety == "SAFE":
                        safety = "CAUTION"
                        reason += " (recently modified, under retention period)"

                    items.append(
                        FileItem(
                            path=entry,
                            size_bytes=stat.st_size,
                            modified_time=mtime,
                            category=target.category,
                            safety_level=safety,
                            reason=reason,
                        )
                    )
                except (PermissionError, FileNotFoundError, OSError):
                    continue
        except (PermissionError, OSError):
            pass

        return items

    def scan_all(self) -> ScanReport:
        report = ScanReport()
        for target in self.get_known_targets():
            items = self.scan_location(target)
            for item in items:
                report.scanned_files_count += 1
                report.total_scanned_bytes += item.size_bytes
                report.category_totals[item.category] = (
                    report.category_totals.get(item.category, 0) + item.size_bytes
                )
                report.items.append(item)
        return report


def purge_items(items: List[FileItem], dry_run: bool = True) -> Tuple[int, int]:
    """Purges given items. Returns (reclaimed_bytes, deleted_count)."""
    reclaimed_bytes = 0
    deleted_count = 0

    for item in items:
        if dry_run:
            reclaimed_bytes += item.size_bytes
            deleted_count += 1
        else:
            try:
                if item.path.is_file():
                    item.path.unlink()
                    reclaimed_bytes += item.size_bytes
                    deleted_count += 1
            except (PermissionError, FileNotFoundError, OSError):
                continue

    return reclaimed_bytes, deleted_count
